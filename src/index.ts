import { Hono } from 'hono'
import { modpacks } from './routes/modpacks'

const app = new Hono()

// ============================================================
// API
// ============================================================

app.get('/api', (c) => {
    return c.json({
        name: 'BlockForge API',
        version: '1.0.0',
        status: 'online'
    })
})


// ============================================================
// ROUTES
// ============================================================

app.route('/api/v1/modpacks', modpacks)


// ============================================================
// EXPORT
// ============================================================

export default app